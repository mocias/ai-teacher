const assert=require('node:assert/strict');
const {writeFileSync}=require('node:fs');
const {join}=require('node:path');
exports.run=async(main)=>{
 const exec=code=>main.webContents.executeJavaScript(code);
 const until=async(check,label)=>{for(let i=0;i<150;i++){if(await check())return;await new Promise(resolve=>setTimeout(resolve,100));}throw Error('DSH UI timed out: '+label);};
 const click=selector=>exec(`document.querySelector(${JSON.stringify(selector)}).click()`);
 const set=(selector,value)=>exec(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('change',{bubbles:true}));})()`);
 await click('[data-view="models"]');await click('[data-action="agent-configure"][data-id="master"]');
 await until(()=>exec(`!!document.querySelector('#agent-mode')`),'configuration dialog');
 await set('#agent-mode','MCP');await set('#agent-harness','DSH');
 await until(()=>exec(`document.querySelector('#agent-dsh-status')?.textContent.startsWith('已找到 DSH')`),'automatic detection');
 assert.equal(await exec(`document.querySelector('input[name=executable]').value`),'');
 const detected=await exec(`fetch('/api/agents/detect-dsh',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'}).then(r=>r.json())`);
 assert.equal(detected.found,true);assert.ok((await exec(`document.querySelector('#agent-dsh-status').textContent`)).includes(detected.executable));
 await click('#agent-dsh-detect');await until(()=>exec(`!document.querySelector('#agent-dsh-detect').disabled`),'refresh detection');
 assert.ok((await exec(`document.querySelector('#agent-dsh-status').textContent`)).includes(detected.executable));
 await exec(`new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve(true))))`);
 if(process.env.TEACHER_SMOKE_OUTPUT)writeFileSync(join(process.env.TEACHER_SMOKE_OUTPUT,'dsh-detected.png'),(await main.webContents.capturePage()).toPNG());
 await click('#dialog-form button[type=submit]');await until(()=>exec(`!document.querySelector('#editor').open`),'save automatic path');
 const route=await exec(`fetch('/api/state').then(r=>r.json()).then(s=>s.agents.routes.find(r=>r.role==='master'))`);
 assert.equal(route.harness,'DSH');assert.equal(route.executable,'');
 await main.webContents.reload();await until(()=>exec(`!!document.querySelector('[data-view="models"]')`),'reload');
 await click('[data-view="models"]');await click('[data-action="agent-configure"][data-id="master"]');
 await until(()=>exec(`document.querySelector('#agent-dsh-status')?.textContent.startsWith('已找到 DSH')`),'persisted route detects again');
 assert.equal(await exec(`document.querySelector('input[name=executable]').value`),'');
 await click('[data-action="close-dialog"]');
 assert.ok(await exec(`document.querySelector('#dsh-sessions')?.textContent.includes('AI Teacher 的所有相关对话共用一个工作区')`));
 const result={automaticDetection:true,refreshDetection:true,emptyPathSaved:true,reloadPreserved:true,executable:detected.executable,version:detected.version};
 if(process.env.TEACHER_SMOKE_OUTPUT)writeFileSync(join(process.env.TEACHER_SMOKE_OUTPUT,'dsh-result.json'),JSON.stringify(result,null,2));
 console.log('DSH_SMOKE_OK '+JSON.stringify(result));
};
